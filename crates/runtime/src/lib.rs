fn selected_openapi_sha256(source: Option<&str>) -> Result<&'static str, RuntimeError> {
    match source.unwrap_or("upstream") {
        "upstream" => Ok(OPENCODE_OPENAPI_SHA256),
        "fork" => Ok(OPENCODE_FORK_OPENAPI_SHA256),
        source => Err(RuntimeError::Rejected(format!(
            "PERSONAL_AGENT_OPENCODE_SOURCE must be upstream or fork, found {source}"
        ))),
    }
}

fn use_fork_session_environment(
    source: Option<&str>,
    has_environment: bool,
) -> Result<bool, RuntimeError> {
    match source.unwrap_or("upstream") {
        "upstream" if has_environment => Err(RuntimeError::Rejected(
            "per-session environment variables are not supported by the pinned runtime API".into(),
        )),
        "upstream" => Ok(false),
        "fork" => Ok(has_environment),
        source => Err(RuntimeError::Rejected(format!(
            "PERSONAL_AGENT_OPENCODE_SOURCE must be upstream or fork, found {source}"
        ))),
    }
}

