struct NativeToolBridge {
    endpoint: Url,
    token: SecretString,
    gateway: Arc<tokio::sync::Mutex<ToolGateway>>,
    task: JoinHandle<()>,
}

impl NativeToolBridge {
    async fn start(sessions: Arc<RwLock<BTreeMap<String, PathBuf>>>) -> Result<Self, RuntimeError> {
        let listener = TokioTcpListener::bind(("127.0.0.1", 0)).await?;
        let address = listener.local_addr()?;
        let endpoint = Url::parse(&format!(
            "http://127.0.0.1:{}/v1/tools/runtime-status",
            address.port()
        ))
        .expect("native bridge loopback URL");
        let token = SecretString::from(Uuid::new_v4().to_string());
        let token_for_task = token.expose_secret().to_owned();
        let mut gateway = ToolGateway::new(16 * 1024);
        gateway.register(Arc::new(RuntimeStatusTool::new()));
        let gateway = Arc::new(tokio::sync::Mutex::new(gateway));
        let gateway_for_task = Arc::clone(&gateway);
        let task = tokio::spawn(async move {
            loop {
                let Ok((stream, peer)) = listener.accept().await else {
                    break;
                };
                if !peer.ip().is_loopback() {
                    continue;
                }
                let gateway = Arc::clone(&gateway_for_task);
                let sessions = Arc::clone(&sessions);
                let token = token_for_task.clone();
                tokio::spawn(async move {
                    let _ = handle_bridge_connection(stream, &token, gateway, sessions).await;
                });
            }
        });
        Ok(Self {
            endpoint,
            token,
            gateway,
            task,
        })
    }

    async fn audit_count(&self) -> usize {
        self.gateway.lock().await.audits().len()
    }
}

impl Drop for NativeToolBridge {
    fn drop(&mut self) {
        self.task.abort();
    }
}

async fn handle_bridge_connection(
    mut stream: TcpStream,
    token: &str,
    gateway: Arc<tokio::sync::Mutex<ToolGateway>>,
    sessions: Arc<RwLock<BTreeMap<String, PathBuf>>>,
) -> Result<(), std::io::Error> {
    let response = match read_bridge_request(&mut stream).await {
        Ok((authorization, request)) if authorization == format!("Bearer {token}") => {
            execute_bridge_request(request, gateway, sessions).await
        }
        Ok(_) => (401, serde_json::json!({"error":"unauthorized"})),
        Err(status) => (status, serde_json::json!({"error":"invalid request"})),
    };
    write_bridge_response(&mut stream, response.0, &response.1).await
}

async fn read_bridge_request(stream: &mut TcpStream) -> Result<(String, BridgeRequest), u16> {
    const MAX_REQUEST_BYTES: usize = 32 * 1024;
    let mut bytes = Vec::with_capacity(2048);
    let header_end = loop {
        if bytes.len() >= MAX_REQUEST_BYTES {
            return Err(413);
        }
        let mut chunk = [0_u8; 2048];
        let count = stream.read(&mut chunk).await.map_err(|_| 400_u16)?;
        if count == 0 {
            return Err(400);
        }
        bytes.extend_from_slice(&chunk[..count]);
        if let Some(index) = bytes.windows(4).position(|window| window == b"\r\n\r\n") {
            break index + 4;
        }
    };
    let headers = std::str::from_utf8(&bytes[..header_end]).map_err(|_| 400_u16)?;
    let mut lines = headers.split("\r\n");
    if lines.next() != Some("POST /v1/tools/runtime-status HTTP/1.1") {
        return Err(404);
    }
    let mut authorization = None;
    let mut content_length = None;
    for line in lines {
        let Some((name, value)) = line.split_once(':') else {
            continue;
        };
        match name.trim().to_ascii_lowercase().as_str() {
            "authorization" => authorization = Some(value.trim().to_owned()),
            "content-length" => {
                content_length = Some(value.trim().parse::<usize>().map_err(|_| 400_u16)?);
            }
            _ => {}
        }
    }
    let content_length = content_length.ok_or(411_u16)?;
    if header_end.saturating_add(content_length) > MAX_REQUEST_BYTES {
        return Err(413);
    }
    while bytes.len() < header_end + content_length {
        let mut chunk = [0_u8; 2048];
        let count = stream.read(&mut chunk).await.map_err(|_| 400_u16)?;
        if count == 0 {
            return Err(400);
        }
        bytes.extend_from_slice(&chunk[..count]);
        if bytes.len() > MAX_REQUEST_BYTES {
            return Err(413);
        }
    }
    let request = serde_json::from_slice(&bytes[header_end..header_end + content_length])
        .map_err(|_| 400_u16)?;
    Ok((authorization.ok_or(401_u16)?, request))
}

async fn execute_bridge_request(
    request: BridgeRequest,
    gateway: Arc<tokio::sync::Mutex<ToolGateway>>,
    sessions: Arc<RwLock<BTreeMap<String, PathBuf>>>,
) -> (u16, Value) {
    let Ok(directory) = std::fs::canonicalize(&request.directory) else {
        return (403, serde_json::json!({"error":"session scope denied"}));
    };
    let authorized = sessions
        .read()
        .ok()
        .and_then(|registered| registered.get(&request.session_id).cloned())
        .is_some_and(|registered| registered == directory);
    if !authorized {
        return (403, serde_json::json!({"error":"session scope denied"}));
    }
    if request.operation.as_deref() == Some("authorize") {
        let Some(tool) = request.tool.as_deref() else {
            return (400, serde_json::json!({"error":"coding tool is required"}));
        };
        return match authorize_coding_tool(tool, &request.arguments, &directory) {
            Ok(()) => (
                200,
                serde_json::json!({"authorized":true,"tool":tool,"boundary":"native-tool-gateway"}),
            ),
            Err(reason) => (403, serde_json::json!({"error":reason})),
        };
    }
    let call = ToolCall {
        call_id: Uuid::now_v7(),
        goal_id: Uuid::nil(),
        task_id: None,
        tool_id: "runtime.status".into(),
        target: directory.display().to_string(),
        input: serde_json::json!({}),
        input_zones: BTreeSet::from([DataZone::AgentGenerated]),
        granted_scopes: BTreeSet::from(["runtime.observe".into()]),
        estimated_cost_usd: 0.0,
        background: false,
        user_present: true,
        checkpoint_available: false,
    };
    match gateway.lock().await.call(call, &[]).await {
        Ok(output) => (200, output.value),
        Err(_) => (403, serde_json::json!({"error":"tool call denied"})),
    }
}

fn authorize_coding_tool(tool: &str, arguments: &Value, directory: &Path) -> Result<(), String> {
    const CODING_TOOLS: &[&str] = &[
        "apply_patch",
        "bash",
        "edit",
        "execute",
        "glob",
        "grep",
        "list",
        "lsp",
        "patch",
        "read",
        "skill",
        "task",
        "todoread",
        "todowrite",
        "webfetch",
        "websearch",
        "write",
    ];
    if !CODING_TOOLS.contains(&tool) {
        return Err("coding tool is not in the reviewed native allowlist".into());
    }
    let object = arguments
        .as_object()
        .ok_or_else(|| "coding tool arguments must be an object".to_owned())?;
    for key in ["filePath", "path", "cwd", "workdir"] {
        if let Some(path) = object.get(key).and_then(Value::as_str)
            && !path_is_within_workspace(directory, path)
        {
            return Err(format!("{key} leaves the registered session workspace"));
        }
    }
    if matches!(tool, "apply_patch" | "patch") {
        let patch_text = object
            .get("patchText")
            .and_then(Value::as_str)
            .ok_or_else(|| "apply_patch patchText is required".to_owned())?;
        validate_patch_paths(directory, patch_text)?;
    }
    if tool == "bash" {
        let command = object
            .get("command")
            .and_then(Value::as_str)
            .ok_or_else(|| "bash command is required".to_owned())?;
        if command.is_empty() || command.len() > 16 * 1024 || command.contains('\0') {
            return Err("bash command is empty or exceeds the native limit".into());
        }
        if destructive_shell_command(command) {
            return Err("destructive or privileged shell command is blocked natively".into());
        }
    }
    Ok(())
}

fn destructive_shell_command(command: &str) -> bool {
    let normalized = normalize_shell_command(command);
    let words = split_shell_words(&normalized)
        .unwrap_or_else(|| normalized.split_whitespace().map(str::to_owned).collect());

    if destructive_token_sequence(&words) || redirects_to_raw_block_device(&words) {
        return true;
    }

    // Token matching is the primary check. Keep the coarse substring pass as a second net for
    // malformed shell fragments and syntax that the deliberately small tokenizer does not model.
    [
        "rm -rf",
        "git reset --hard",
        "git clean -",
        "sudo ",
        "doas ",
        "mkfs",
        "shutdown",
        "reboot",
        "> /dev/",
    ]
    .iter()
    .any(|forbidden| normalized.contains(forbidden))
}

fn normalize_shell_command(command: &str) -> String {
    let collapsed = command
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .to_ascii_lowercase();
    let argv0_end = collapsed
        .find(char::is_whitespace)
        .unwrap_or(collapsed.len());
    let argv0 = &collapsed[..argv0_end];
    let bytes = argv0.as_bytes();
    if bytes.len() >= 2 && matches!(bytes[0], b'\'' | b'"') && bytes.last() == bytes.first() {
        format!("{}{}", &argv0[1..argv0.len() - 1], &collapsed[argv0_end..])
    } else {
        collapsed
    }
}

#[derive(Clone, Copy, Eq, PartialEq)]
enum ShellQuote {
    Single,
    Double,
}

fn split_shell_words(command: &str) -> Option<Vec<String>> {
    let mut words = Vec::new();
    let mut word = String::new();
    let mut started = false;
    let mut quote = None;
    let mut chars = command.chars();

    while let Some(character) = chars.next() {
        match quote {
            Some(ShellQuote::Single) => {
                if character == '\'' {
                    quote = None;
                } else {
                    word.push(character);
                }
            }
            Some(ShellQuote::Double) => match character {
                '"' => quote = None,
                '\\' => word.push(chars.next()?),
                _ => word.push(character),
            },
            None => match character {
                '\'' => {
                    quote = Some(ShellQuote::Single);
                    started = true;
                }
                '"' => {
                    quote = Some(ShellQuote::Double);
                    started = true;
                }
                '\\' => {
                    word.push(chars.next()?);
                    started = true;
                }
                value if value.is_whitespace() => {
                    if started {
                        words.push(std::mem::take(&mut word));
                        started = false;
                    }
                }
                _ => {
                    word.push(character);
                    started = true;
                }
            },
        }
    }

    if quote.is_some() {
        return None;
    }
    if started {
        words.push(word);
    }
    Some(words)
}

fn shell_command_word(word: &str) -> &str {
    word.trim_matches(|character| matches!(character, '$' | '(' | ')' | '`' | ';'))
}

fn destructive_token_sequence(words: &[String]) -> bool {
    let argv0_index = usize::from(
        words
            .first()
            .is_some_and(|word| shell_command_word(word) == "command"),
    );
    if let Some(argv0) = words.get(argv0_index).map(|word| shell_command_word(word))
        && (matches!(argv0, "sudo" | "doas" | "shutdown" | "reboot") || argv0.starts_with("mkfs"))
    {
        return true;
    }

    for (index, word) in words.iter().enumerate() {
        match shell_command_word(word) {
            "rm" => {
                let first_flag = words.get(index + 1).map(|word| shell_command_word(word));
                let second_flag = words.get(index + 2).map(|word| shell_command_word(word));
                if matches!(first_flag, Some("-rf" | "-fr"))
                    || (first_flag == Some("-r") && second_flag == Some("-f"))
                {
                    return true;
                }
            }
            "git" => {
                let operation = words.get(index + 1).map(|word| shell_command_word(word));
                let option = words.get(index + 2).map(|word| shell_command_word(word));
                if operation == Some("clean")
                    || (operation == Some("reset") && option == Some("--hard"))
                {
                    return true;
                }
            }
            _ => {}
        }
    }
    false
}

fn redirects_to_raw_block_device(words: &[String]) -> bool {
    words.iter().enumerate().any(|(index, word)| {
        let Some(redirection) = word.rfind('>') else {
            return false;
        };
        let inline_target = &word[redirection + 1..];
        let target = if inline_target.is_empty() {
            words.get(index + 1).map_or("", String::as_str)
        } else {
            inline_target
        };
        let target = shell_command_word(target);
        target.starts_with("/dev/sd") || target.starts_with("/dev/nvme")
    })
}

fn validate_patch_paths(workspace: &Path, patch_text: &str) -> Result<(), String> {
    const PATH_MARKERS: &[&str] = &[
        "*** Add File: ",
        "*** Update File: ",
        "*** Delete File: ",
        "*** Move to: ",
    ];
    let mut found = false;
    for line in patch_text.lines() {
        let Some(target) = PATH_MARKERS
            .iter()
            .find_map(|marker| line.strip_prefix(marker))
        else {
            continue;
        };
        found = true;
        if !path_is_within_workspace(workspace, target.trim()) {
            return Err("apply_patch target leaves the registered session workspace".into());
        }
    }
    if !found {
        return Err("apply_patch contains no reviewed file target".into());
    }
    Ok(())
}

fn path_is_within_workspace(workspace: &Path, value: &str) -> bool {
    if value.is_empty() || value.contains('\0') {
        return false;
    }
    let input = Path::new(value);
    let candidate = if input.is_absolute() {
        input.to_path_buf()
    } else {
        workspace.join(input)
    };
    if let Ok(canonical) = std::fs::canonicalize(&candidate) {
        return canonical.starts_with(workspace);
    }
    let mut ancestor = candidate.as_path();
    while !ancestor.exists() {
        let Some(parent) = ancestor.parent() else {
            return false;
        };
        ancestor = parent;
    }
    std::fs::canonicalize(ancestor).is_ok_and(|canonical| canonical.starts_with(workspace))
}

async fn write_bridge_response(
    stream: &mut TcpStream,
    status: u16,
    body: &Value,
) -> Result<(), std::io::Error> {
    let encoded = serde_json::to_vec(body).unwrap_or_else(|_| b"{}".to_vec());
    let reason = match status {
        200 => "OK",
        400 => "Bad Request",
        401 => "Unauthorized",
        403 => "Forbidden",
        404 => "Not Found",
        411 => "Length Required",
        413 => "Payload Too Large",
        _ => "Error",
    };
    let headers = format!(
        "HTTP/1.1 {status} {reason}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
        encoded.len()
    );
    stream.write_all(headers.as_bytes()).await?;
    stream.write_all(&encoded).await?;
    stream.shutdown().await
}

